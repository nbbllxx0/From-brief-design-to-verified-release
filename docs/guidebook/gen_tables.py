LOCAL_PATH = re.compile(r"[A-Za-z]:[/\\][^\s`'\")]*")


def scrub(s: str) -> str:
    def rep(m):
        p = m.group(0)
        return "python" if p.lower().endswith("python.exe") else "<path>"
    return LOCAL_PATH.sub(rep, s)


