"""Generate the guidebook's reference tables from the code, so the book stays in sync with it.

    python -B docs/guidebook/gen_tables.py          (the agentto environment: pydantic and numpy)

Reads, never writes outside docs/guidebook/generated/:
    src/agentto/spec.py           the spec schema (live pydantic model), compared with schemas/spec_v0.schema.json
    src/agentto/rules.py          rule codes, severities, messages and one-click fixes (parsed, not imported:
                                  importing rules.py would import the solver package)
    src/agentto/problem.py        the R001 message
    src/agentto/tools.py          the tool registry (imported): names, profiles, arguments, docstrings
    src/agentto/solver.py         certificate predicates and record fields, continuation schedules (parsed)
    src/agentto/escalation.py     the cold and long re-opening schedules (parsed)
    src/agentto/worker.py         ladder limits and solver choice (parsed)
    src/agentto/export.py         design-report fields (parsed)
    src/agentto/mcp_server.py     command-line flags (parsed)
    web/src/components/*.tsx      keyboard map and certificate labels (parsed)
    scripts/*.py                  script catalogue (module docstrings)

Explanatory prose that the code does not contain (what a rule means, how to fix it) is kept here in dictionaries
keyed by code. The script stops with an error if the code gains or loses a key that has no explanation, so a new
rule, tool or certificate check cannot silently go undocumented. A final lint refuses local paths in the book.
"""
