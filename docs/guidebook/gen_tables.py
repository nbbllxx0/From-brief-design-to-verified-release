def fmt_schema_type(p: dict) -> str:
    if "$ref" in p:
        n = p["$ref"].split("/")[-1]
        return f"\\hyperref[sch:{n}]{{\\code{{{n}}}}}"
    if "const" in p:
        return f"\\code{{\"{esc(p['const'])}\"}} (fixed)"
    if "enum" in p:
        return "one of " + ", ".join(code(v) for v in p["enum"])
    if "oneOf" in p:
        names = [x["$ref"].split("/")[-1] for x in p["oneOf"]]
        return "region: " + ", ".join(f"\\hyperref[sch:{n}]{{\\code{{{n[:-6].lower()}}}}}" for n in names)
    if "anyOf" in p:
        parts = [x for x in p["anyOf"] if x.get("type") != "null"]
        base = fmt_schema_type(parts[0]) if len(parts) == 1 else " or ".join(fmt_schema_type(x) for x in parts)
        return base + " or \\code{null}"
    t = p.get("type")
    if t == "array":
        if "prefixItems" in p:
            return f"[{p['prefixItems'][0].get('type', 'value')} $\\times$ {len(p['prefixItems'])}]"
        it = p.get("items", {})
        return "list of " + fmt_schema_type(it)
    if t == "object":
        return "object"
    return {"number": "number", "integer": "integer", "string": "string", "boolean": "boolean"}.get(t, str(t))


def constraints(p: dict) -> list[str]:
    c = []
    q = p
    if "anyOf" in p:
        nn = [x for x in p["anyOf"] if x.get("type") != "null"]
        q = nn[0] if len(nn) == 1 else p
    for k, sym in (("exclusiveMinimum", ">"), ("minimum", r"\ge"), ("exclusiveMaximum", "<"), ("maximum", r"\le")):
        if k in q:
            c.append(f"${sym} {q[k]:g}$")
    if "minItems" in q and q.get("type") == "array" and "prefixItems" not in q:
        c.append(f"at least {q['minItems']}")
    return c


def fmt_default(v) -> str:
    if v is None:
        return r"\code{null}"
    if isinstance(v, (dict, list)):
        return code(json.dumps(v, separators=(", ", ": ")))
    if isinstance(v, str):
        return code(json.dumps(v))
    return code(json.dumps(v))


def schema_tables(live: dict) -> str:
    defs = live["$defs"]
    require_keys("schema objects", ["Spec", *defs], {k: 1 for k in SCHEMA_ORDER})
    out = []
    for name in SCHEMA_ORDER:
        d = live if name == "Spec" else defs[name]
        req = set(d.get("required", []))
        # keep each small table with its heading (rows can wrap, so allow about two lines per field)
        need = min(6 + round(1.5 * len(d["properties"])), 16)
        out.append(f"\\needspace{{{need}\\baselineskip}}")
        out.append(f"\\section{{\\texorpdfstring{{\\code{{{name}}}}}{{{name}}}}}\\label{{sch:{name}}}")
        out.append(SCHEMA_INTRO[name] + "\n")
        out.append(r"\begin{reftable}{@{}>{\raggedright\arraybackslash}p{0.19\linewidth}"
                   r">{\raggedright\arraybackslash}p{0.30\linewidth}"
                   r">{\raggedright\arraybackslash}p{0.17\linewidth}"
                   r">{\raggedright\arraybackslash}X@{}}")
        out.append(r"Field & Type & Default & Constraints and notes \\ \midrule")
        for f, p in d["properties"].items():
            dflt = r"\emph{required}" if f in req else (fmt_default(p["default"]) if "default" in p else "--")
            notes = constraints(p)
            if p.get("description"):
                notes.append(esc(p["description"]))
            out.append(f"{code(f)} & {fmt_schema_type(p)} & {dflt} & {'; '.join(notes)} \\\\")
        out.append(r"\end{reftable}" + "\n")
    return "\n".join(out)


def schema_drift(live: dict, file: dict) -> list[str]:
    """Differences between the live model and the exported schema file, at the level a user would notice."""
    diffs = []
    L = {"Spec": live, **live["$defs"]}
    F = {"Spec": file, **file.get("$defs", {})}
    for n in sorted(set(L) | set(F)):
        if n not in F:
            diffs.append(f"object {n} is missing from the file")
            continue
        if n not in L:
            diffs.append(f"object {n} is in the file but not in spec.py")
            continue
        lp, fp = L[n].get("properties", {}), F[n].get("properties", {})
        for k in sorted(set(lp) - set(fp)):
            diffs.append(f"{n}.{k} is missing from the file")
        for k in sorted(set(fp) - set(lp)):
            diffs.append(f"{n}.{k} is in the file but not in spec.py")
        for k in sorted(set(lp) & set(fp)):
            a, b = dict(lp[k]), dict(fp[k])
            if a != b:
                diffs.append(f"{n}.{k} differs")
        if L[n].get("required", []) != F[n].get("required", []):
            diffs.append(f"{n}: required fields differ")
    return diffs


