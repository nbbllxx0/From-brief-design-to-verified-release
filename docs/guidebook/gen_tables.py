def fmt_py_type(t) -> str:
    from agentto import spec as S
    if t is S.Vec3:
        return "[x, y, z]"
    if t is S.Vec2:
        return "[a, b]"
    if t is S.NodeRegion:
        return "region (face, patch, edge, box, cylinder)"
    if t is S.VolumeRegion:
        return "region (box, cylinder)"
    o, a = typing.get_origin(t), typing.get_args(t)
    if o is typing.Literal:
        return " | ".join(code(x) for x in a)
    if o in (typing.Union, getattr(__import__("types"), "UnionType", None)):
        nn = [x for x in a if x is not type(None)]
        base = " or ".join(fmt_py_type(x) for x in nn)
        return base + (", optional" if len(nn) < len(a) else "")
    if o is list:
        inner = a[0]
        if getattr(inner, "__name__", "") == "ClarifyOption":
            return "list of options (see below)"
        return "list of " + fmt_py_type(inner)
    if o is typing.Annotated:
        return fmt_py_type(a[0])
    if t is dict:
        return "object"
    return {str: "string", float: "number", int: "integer", bool: "boolean"}.get(t, esc(getattr(t, "__name__", t)))


def fmt_py_default(p) -> str:
    if p.default is inspect.Parameter.empty:
        return r"\emph{required}"
    if p.default is None:
        return "--"
    return code(json.dumps(p.default))


