UNI = {"×": r"$\times$", "−": r"$-$", "–": "--", "—": "---", "ρ": r"$\rho$", "ν": r"$\nu$", "≤": r"$\le$",
       "≥": r"$\ge$", "→": r"$\rightarrow$", "≈": r"$\approx$", "…": r"\ldots{}", "³": r"$^3$", "²": r"$^2$",
       "·": r"$\cdot$", "‘": "`", "’": "'", "“": "``", "”": "''", "°": r"$^\circ$", "β": r"$\beta$",
       "Δ": r"$\Delta$", "μ": r"$\mu$", "±": r"$\pm$", "⁸": r"$^8$", "⁻": r"$^-$", "⁶": r"$^6$", "✓": "yes",
       "✗": "no", "↑": r"$\uparrow$", "|": r"\textbar{}"}


def esc(s) -> str:
    s = str(s)
    out = []
    for ch in s:
        if ch == "\\":
            out.append(r"\textbackslash{}")
        elif ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        elif ch in UNI:
            out.append(UNI[ch])
        elif ord(ch) > 127:
            raise ValueError(f"no LaTeX mapping for {ch!r} in {s!r}")
        elif ch == "-" and out and out[-1] == "-":
            out.append("{}-")  # keep "--attach" from becoming an en dash in prose fonts
        else:
            out.append(ch)
    return "".join(out)


def code(s) -> str:
    """Inline code with break points after _ . / , and spaces kept."""
    t = esc(s)
    t = t.replace(r"\_", r"\_\allowbreak{}").replace("/", r"/\allowbreak{}").replace(",", r",\allowbreak{}")
    return r"\code{" + t + "}"


def sci(x: float) -> str:
    """8e7 -> $8\\times10^{7}$; small numbers as they are."""
    if x == 0:
        return "0"
    e = int(f"{x:e}".split("e")[1])
    if -3 <= e <= 4:
        return f"{x:g}"
    m = x / 10 ** e
    ms = f"{m:g}"
    return f"${ms}\\times10^{{{e}}}$" if ms != "1" else f"$10^{{{e}}}$"


def write(name: str, text: str):
    OUT.mkdir(exist_ok=True)
    p = OUT / name
    p.write_text("% Generated by docs/guidebook/gen_tables.py from the code. Do not edit by hand.\n" + text,
                 encoding="utf-8")
    print(f"  wrote generated/{name}")


def parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"))


def src_of(path: Path, node) -> str:
    return ast.get_source_segment(path.read_text(encoding="utf-8"), node)


def require_keys(what: str, found, documented: dict):
    found, doc = set(found), set(documented)
    if found != doc:
        raise SystemExit(f"{what}: code and guidebook disagree. Undocumented: {sorted(found - doc)}; "
                         f"documented but gone: {sorted(doc - found)}. Update gen_tables.py.")


